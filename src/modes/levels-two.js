// The puzzle mode's second set of levels, and the one a player who is stuck on the first can go
// and play instead. Everything about how a layout is written, what par and floor mean and how both
// are proved is in levels.js; this file is the boards.
//
// None of them is a board from the first set, and that is checked for mirrors and for recoloured
// copies as well as for exact ones: a mirrored board plays identically, and a board with two colours
// swapped is the same puzzle wearing different paint.
//
// Where they came from, since it is not the same place the first set came from. From about 5 upwards
// they were climbed by tools/find-levels.mjs like everything else. Below that no search can reach:
// a keep there needs greed to miss par, which is worth 1.5 of the difficulty score on its own, so
// nothing a run keeps measures under about 5. The opening was drawn and measured instead - small
// silhouettes, colours grown as regions, kept only where the numbers landed in range.
//
// The order is by measured difficulty as far as the last twelve, rising from 2.0 to 11.6. The last
// twelve are arranged rather than sorted, all of them above everything before them, with five steps
// down in them and the hardest board in the set at the end. Bands run 3, 6, 16, 11, 16, which is a
// gentler middle than the first set's 2, 1, 9, 15, 25 and the reason this is the set to come to when
// the first one has stopped being fun.

